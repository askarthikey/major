"""
Dataset-agnostic data loader for household energy data.

Supports loading from:
- Pecan Street Dataport (1-min resolution residential solar + load)
- REFIT (UK household electricity data)
- UK-DALE (UK domestic appliance-level electricity)
- Synthetic data (generated by this system)
- Any CSV with the common schema: timestamp, household_id, load_kw, solar_kw

The loader normalizes all datasets to a common schema, handles resampling
(e.g., 1-min → 15-min), and provides train/val/test splits based on time
(not random — to avoid temporal leakage).
"""

import pandas as pd
import numpy as np
import torch
from torch.utils.data import Dataset
from torch_geometric.data import Data, InMemoryDataset
from pathlib import Path
from typing import Tuple, Optional, List, Dict
import json
import logging

from config.settings import settings

logger = logging.getLogger(__name__)


class TradeDataset(Dataset):
    """
    PyTorch Dataset for GNN training data.

    Loads pre-generated training data (from trade_simulator.py) and converts
    each sample into a PyG Data object on-the-fly.
    """

    def __init__(
        self,
        data_path: str,
        split: str = "train",  # "train", "val", "test"
        train_ratio: float = 0.7,
        val_ratio: float = 0.15,
        # test_ratio is implicitly 1 - train_ratio - val_ratio
    ):
        """
        Args:
            data_path: Path to the training data parquet/csv file.
            split: Which split to use.
            train_ratio: Fraction of data for training.
            val_ratio: Fraction of data for validation.
        """
        self.split = split

        # Load data
        path = Path(data_path)
        if path.suffix == ".parquet":
            self.df = pd.read_parquet(path)
        else:
            self.df = pd.read_csv(path)

        # Time-based split (by timestep_idx, not random)
        # This prevents temporal leakage — the model is tested on future timesteps
        unique_timesteps = sorted(self.df["timestep_idx"].unique())
        n_timesteps = len(unique_timesteps)

        train_end = int(n_timesteps * train_ratio)
        val_end = int(n_timesteps * (train_ratio + val_ratio))

        if split == "train":
            valid_timesteps = set(unique_timesteps[:train_end])
        elif split == "val":
            valid_timesteps = set(unique_timesteps[train_end:val_end])
        else:  # test
            valid_timesteps = set(unique_timesteps[val_end:])

        self.df = self.df[self.df["timestep_idx"].isin(valid_timesteps)].reset_index(drop=True)

        logger.info(
            f"TradeDataset ({split}): {len(self.df)} samples, "
            f"timesteps {min(valid_timesteps)}-{max(valid_timesteps)}"
        )

    def __len__(self) -> int:
        return len(self.df)

    def __getitem__(self, idx: int) -> Dict:
        """
        Get a training sample as a dictionary of tensors.

        Returns a flat tensor representation (for both GNN and MLP baseline).
        The GNN model will convert this to a proper PyG Data object.
        """
        row = self.df.iloc[idx]

        # Parse JSON fields
        bus_voltages = json.loads(row["bus_voltages_json"]) if pd.notna(row.get("bus_voltages_json")) else {}
        line_loadings = json.loads(row["line_loadings_json"]) if pd.notna(row.get("line_loadings_json")) else {}
        voltage_deltas = json.loads(row["voltage_deltas_json"]) if pd.notna(row.get("voltage_deltas_json")) else {}

        # Scalar features
        features = {
            "seller_bus": int(row["seller_bus"]),
            "buyer_bus": int(row["buyer_bus"]),
            "amount_kw": float(row["amount_kw"]),
            "seller_surplus_kw": float(row["seller_surplus_kw"]),
            "buyer_load_kw": float(row["buyer_load_kw"]),
            "baseline_max_v_dev": float(row["baseline_max_v_dev"]),
            "baseline_max_line_load": float(row["baseline_max_line_load"]),
            "timestep_idx": int(row["timestep_idx"]),
        }

        # Flatten bus voltages and line loadings into fixed-size vectors
        # (pad/truncate to a fixed number of buses/lines)
        max_buses = 13
        max_lines = 11

        voltage_vector = np.zeros(max_buses, dtype=np.float32)
        for k, v in bus_voltages.items():
            idx_int = int(k)
            if idx_int < max_buses:
                voltage_vector[idx_int] = v

        loading_vector = np.zeros(max_lines, dtype=np.float32)
        for k, v in line_loadings.items():
            idx_int = int(k)
            if idx_int < max_lines:
                loading_vector[idx_int] = v / 100.0  # Normalize

        # Target
        label = float(row["is_feasible"])

        return {
            "features": features,
            "bus_voltages": torch.tensor(voltage_vector),
            "line_loadings": torch.tensor(loading_vector),
            "label": torch.tensor([label], dtype=torch.float32),
            "trade_max_v_dev": torch.tensor([float(row["trade_max_v_dev"])]),
            "trade_max_line_load": torch.tensor([float(row["trade_max_line_load"]) / 100.0]),
        }


def get_flat_features(sample: Dict) -> torch.Tensor:
    """
    Convert a sample dict to a flat feature tensor for the MLP baseline.

    This flattens all features into a single vector, discarding graph structure.
    The GNN should outperform this — if it doesn't, the graph structure isn't
    helping and we need to investigate why.
    """
    features = sample["features"]
    scalars = torch.tensor([
        features["amount_kw"] / 10.0,
        features["seller_surplus_kw"] / 10.0,
        features["buyer_load_kw"] / 10.0,
        features["baseline_max_v_dev"],
        features["baseline_max_line_load"] / 100.0,
        float(features["seller_bus"]) / 13.0,
        float(features["buyer_bus"]) / 13.0,
        float(features["timestep_idx"]) / 96.0,
    ], dtype=torch.float32)

    return torch.cat([scalars, sample["bus_voltages"], sample["line_loadings"]])


def load_energy_data(
    filepath: str,
    resample_freq: str = "15min",
) -> pd.DataFrame:
    """
    Load and standardize energy data from various dataset formats.

    Handles Pecan Street, REFIT, UK-DALE, and generic CSV formats.
    Resamples to the target frequency (default 15-min intervals).

    Args:
        filepath: Path to the data file.
        resample_freq: Target resampling frequency.

    Returns:
        Standardized DataFrame with columns:
        timestamp, household_id, load_kw, solar_kw
    """
    path = Path(filepath)

    if path.suffix == ".parquet":
        df = pd.read_parquet(path)
    elif path.suffix in (".csv", ".tsv"):
        df = pd.read_csv(path, parse_dates=True)
    else:
        raise ValueError(f"Unsupported file format: {path.suffix}")

    # Standardize column names (handles common naming conventions)
    column_mapping = {
        # Timestamps
        "time": "timestamp",
        "datetime": "timestamp",
        "date_time": "timestamp",
        # Household ID
        "house_id": "household_id",
        "home_id": "household_id",
        "dataid": "household_id",
        "building": "household_id",
        # Load
        "use": "load_kw",
        "grid": "load_kw",
        "power_kw": "load_kw",
        "consumption_kw": "load_kw",
        "aggregate": "load_kw",
        "demand_kw": "load_kw",
        # Solar
        "gen": "solar_kw",
        "solar": "solar_kw",
        "pv_kw": "solar_kw",
        "generation_kw": "solar_kw",
        "solar_generation_kw": "solar_kw",
    }

    df = df.rename(columns={
        k: v for k, v in column_mapping.items()
        if k in df.columns and v not in df.columns
    })

    # Ensure timestamp is datetime
    if "timestamp" in df.columns:
        df["timestamp"] = pd.to_datetime(df["timestamp"])

    # Fill missing solar column
    if "solar_kw" not in df.columns:
        df["solar_kw"] = 0.0

    # Convert household_id to string
    if "household_id" in df.columns:
        df["household_id"] = df["household_id"].astype(str)

    # Resample if needed
    if resample_freq and "timestamp" in df.columns and "household_id" in df.columns:
        df = df.set_index("timestamp")
        df = df.groupby("household_id").resample(resample_freq).mean().reset_index()

    # Ensure non-negative values
    df["load_kw"] = df["load_kw"].clip(lower=0)
    df["solar_kw"] = df["solar_kw"].clip(lower=0)

    logger.info(
        f"Loaded energy data: {len(df)} records, "
        f"{df['household_id'].nunique()} households"
    )
    return df
